//! Opt-in Python/ONNX parity check using real trained keyword bundles.
use anyhow::{Context, Result};
use scan::features::{ExtractContext, FeatureSpec};
use scan::model::{Model, Thresholds};
use serde::Deserialize;

#[derive(Deserialize)]
struct Bundle {
    directory: std::path::PathBuf,
    cases: Vec<Case>,
}

#[derive(Deserialize)]
struct Case {
    name: String,
    report: cleave::types::CompactReport,
    probability: f32,
    #[serde(default)]
    expected_error: Option<String>,
    #[serde(default)]
    expected: Option<Vec<f32>>,
}

#[test]
#[expect(clippy::disallowed_methods, reason = "test-only fixture path")]
#[ignore = "requires SCAN_PARITY_CASES generated by collimator"]
fn collimator_bundles_match_features_and_probabilities() -> Result<()> {
    let path = std::env::var_os("SCAN_PARITY_CASES")
        .or_else(|| std::env::var_os("KEYWORD_BUNDLE_CASES"))
        .context("set SCAN_PARITY_CASES (make test-scan-parity in collimator)")?;
    let bundles: Vec<Bundle> = serde_json::from_slice(&std::fs::read(path)?)?;
    assert!(!bundles.is_empty(), "parity fixture has no bundles");
    for bundle in bundles {
        assert!(!bundle.cases.is_empty(), "parity fixture has no reports");
        let count = bundle.cases.len();
        let mut max_error = 0.0_f32;
        // Each fixture directory is one route; a model loads it as the
        // general route of an ensemble. The thresholds only shape the class,
        // and the comparison is on the probability.
        let ensemble = tempfile::tempdir()?;
        stage_general(&bundle.directory, ensemble.path())?;
        let thresholds = Thresholds {
            suspicious: 0.5,
            hostile: 0.5,
        };
        let model = Model::load(ensemble.path(), Some(thresholds), None)?;
        let spec = FeatureSpec::load(&bundle.directory.join("feature_spec.json"))?;
        let extractor = ExtractContext::new(&spec);
        for case in bundle.cases {
            if let Some(expected_error) = &case.expected_error {
                let error = extractor
                    .try_extract(&case.report)
                    .expect_err("fixture requires an input-contract rejection");
                assert!(error.to_string().contains(expected_error));
                let error = model
                    .predict_report(&case.report)
                    .expect_err("model must enforce the same input contract");
                assert!(error.to_string().contains(expected_error));
                continue;
            }
            if let Some(expected) = &case.expected {
                let actual = extractor.try_extract(&case.report)?;
                assert_eq!(actual.len(), expected.len());
                for (index, (&got, &want)) in actual.iter().zip(expected).enumerate() {
                    let tolerance = 1e-6_f32.max(want.abs() * 1e-5);
                    assert!(
                        (got - want).abs() <= tolerance,
                        "{} {} feature {}: Scan={}, Python={}",
                        bundle.directory.display(),
                        case.name,
                        spec.feature_names()[index],
                        got,
                        want,
                    );
                }
            }
            let (decision, _, _) = model.predict_report(&case.report)?;
            if (decision.probability - case.probability).abs() >= 1e-5
                && let Some(expected) = &case.expected
            {
                let actual = extractor.try_extract(&case.report)?;
                for (index, (&got, &want)) in actual.iter().zip(expected).enumerate() {
                    if got != want {
                        eprintln!(
                            "differing input {}: Scan={got:?}, Python={want:?}",
                            spec.feature_names()[index]
                        );
                    }
                }
            }
            max_error = max_error.max((decision.probability - case.probability).abs());
            assert!(
                (decision.probability - case.probability).abs() < 1e-5,
                "{} {}: Scan={}, Python={}",
                bundle.directory.display(),
                case.name,
                decision.probability,
                case.probability,
            );
        }
        eprintln!(
            "{}: {count} cases, max probability error {max_error:.2e}",
            bundle.directory.display()
        );
    }
    Ok(())
}

/// Copy a route directory's model and spec to `<root>/general`.
fn stage_general(route: &std::path::Path, root: &std::path::Path) -> Result<()> {
    let general = root.join("general");
    std::fs::create_dir_all(&general)?;
    for entry in std::fs::read_dir(route)? {
        let path = entry?.path();
        if path.is_file() {
            std::fs::copy(&path, general.join(path.file_name().context("file name")?))?;
        } else if path.file_name().is_some_and(|n| n == "models") {
            let seeds = general.join("models");
            std::fs::create_dir_all(&seeds)?;
            for seed in std::fs::read_dir(&path)? {
                let seed = seed?.path();
                std::fs::copy(&seed, seeds.join(seed.file_name().context("file name")?))?;
            }
        }
    }
    Ok(())
}
